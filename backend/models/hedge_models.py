from pydantic import BaseModel
from typing import Any, Dict, List, Optional


class InstrumentCandidate(BaseModel):
    # Identity
    instrument_type: str                # "option" | "future" | "forward" | "swap" | "inverse_etf"
    asset_class: str                    # "equity" | "commodity" | "bond" | "fx" | "crypto"
    ticker: str                         # hedge instrument ticker (SPY, QQQ, GLD …)
    strategy: str = ""                  # "Protective Put" | "Bear Put Spread" | "Collar" …

    # Option-specific (None for non-option instruments)
    strike: Optional[float] = None
    expiry_date: Optional[str] = None   # ISO-8601 string (YYYY-MM-DD)
    option_type: Optional[str] = None   # "put" | "call" | None

    # Hedge relationship to the user's position:
    #   "direct_hedge"  — same underlying, MUST be opposite direction (e.g. long MSFT → put MSFT)
    #   "cross_hedge"   — correlated asset / sector ETF (e.g. long MSFT → put QQQ)
    #   "macro_hedge"   — uncorrelated asset used for diversification (e.g. long SPY → long GLD)
    hedge_category: str = "cross_hedge"

    # Multi-leg strategies (spread / collar): short leg details for L6 re-pricing.
    # If set, L6 prices both legs and returns net Greeks / net cost.
    short_strike: Optional[float] = None       # e.g. K_short for bear put spread
    short_option_type: Optional[str] = None    # "put" or "call"

    # Position
    n_contracts: int = 0

    # Cost / protection
    total_cost: float = 0.0             # total premium outlay in dollars
    max_protection: float = 0.0         # max dollar gain from hedge (optional)

    # Greeks (per-contract basis × n_contracts aggregated in engine)
    delta: float = 0.0
    gamma: float = 0.0
    theta: float = 0.0
    vega: float = 0.0
    rho: float = 0.0
    lambda_leverage: float = 0.0        # capital efficiency = Δ × (S / V)

    # Quality metrics
    basis_risk_r2: float = 0.0          # tail correlation / R² of hedge vs asset
    efficiency_ratio: float = 0.0       # |lambda| — leverage per $ of premium

    # What `basis_risk_r2` rests on. An R² of 0.62 from 45 overlapping
    # observations and one from 500 are not the same claim, and the scorer
    # weights basis risk at 15% either way, so the sample has to reach the
    # user with the figure. `basis_risk_source` says what kind of quantity it
    # is: "correlation" is a measured rho² over `basis_risk_window_days`,
    # "tail_correlation" is the bottom-decile correlation, and "identity" is a
    # direct hedge on the same underlying, where R²=1 is definitional rather
    # than estimated — so a blank stderr there means "not applicable", not
    # "not measured". None elsewhere means not measured.
    basis_risk_source: str = ""              # "correlation" | "tail_correlation" | "identity"
    basis_risk_n_obs: Optional[int] = None
    basis_risk_window_days: Optional[int] = None
    basis_risk_stderr: Optional[float] = None

    # Scoring (0–100)
    score: float = 0.0

    # Explanation (filled by LLM layer in Step 5)
    rationale: str = ""
    pros: List[str] = []
    cons: List[str] = []

    # The subset of `cons` that the product asserted itself rather than
    # inherited from an LLM: no executable quote, thin market, expiry crosses
    # earnings. Both explainer layers merge a response by replacing `cons`
    # wholesale, so without a second copy out of the LLM's reach a model that
    # returned its own bullets silently deleted them. See
    # backend/core/disclosures.py — `disclose()` writes this, `restore()`
    # repairs `cons` from it after each merge.
    mandatory_disclosures: List[str] = []
    when_works_best: str = ""
    when_fails: str = ""

    # Partial hedge tradeoff table (generated by position_sizer)
    partial_hedge_options: List[Dict[str, Any]] = []

    # Liquidity metrics (populated by Gap 3 liquidity filter).
    # None means NOT MEASURED — the chain had no two-sided quote for this
    # contract, so depth and spread are unknown. This is deliberately distinct
    # from 0: a bid_ask_spread_pct of 0.0 reads as a perfectly tight market,
    # which is the opposite of the truth when there is no market at all.
    # Outside US market hours the provider clears bid/ask and does not publish
    # open interest, so an entire chain can come back unmeasured.
    liquidity_ok: bool = True           # False if OI < threshold or spread too wide
    open_interest: Optional[int] = None
    daily_volume: Optional[int] = None
    bid_ask_spread_pct: Optional[float] = None   # (ask-bid)/mid — lower is better

    # Earnings flag (Gap 9 — IV crush risk)
    earnings_warning: bool = False      # True if expiry crosses a known earnings date
    earnings_date: Optional[str] = None # ISO date of the earnings event in the window

    # Market premium (Gap 8 — actual market mid price, not BSM)
    market_premium: float = 0.0         # (bid+ask)/2 per contract from live chain
    market_total_cost: float = 0.0      # market_premium × 100 × n_contracts

    # ── Contract identity and pricing provenance ──────────────────────────────
    # A recommendation is only actionable if the contract actually exists. These
    # record the exchange-listed contract the numbers came from, so a strike can
    # never be a model-generated round number presented as tradeable.
    contract_symbol: Optional[str] = None   # OCC symbol, e.g. SPY270129P00655000
    strike_is_listed: bool = False          # True only when verified against the chain
    bid: Optional[float] = None
    ask: Optional[float] = None

    # Short leg of a two-leg structure (bear put spread / collar). Both legs must
    # be real listed contracts for the structure to be executable, so the short
    # leg carries its own OCC symbol.
    short_contract_symbol: Optional[str] = None

    # Premium shown to the user, and where it came from. "market_mid" is a real
    # quote; "model" means the chain had no two-sided quote and the figure is
    # theoretical — the UI must say so rather than implying an executable price.
    premium_source: str = "model"           # "market_mid" | "model"
    model_premium: float = 0.0              # theoretical per-share premium (BSM/CRR)
    premium_vs_model_pct: Optional[float] = None   # market/model - 1

    # Volatility actually used to price this contract.
    iv_used: Optional[float] = None
    iv_source: str = ""     # "contract_iv" | "interpolated_skew" | "atm_iv"
                            # | "garch_forecast" | "realized_vol"

    # Asset-class-specific metrics (populated by L6/L7/L8 engines)
    # IR:       dv01, duration, mod_duration, convexity, yield_level
    # FX:       rho_domestic, rho_foreign, r_domestic, r_foreign
    # Credit:   cs01, dv01, hazard_rate, spread_bps, recovery
    # Commodity: roll_yield_daily
    extended_metrics: Dict[str, Any] = {}


class UnhedgedRisk(BaseModel):
    notional: float             # position notional value in dollars
    # 95% VaR in dollars over `horizon_calendar_days` — the portfolio's hedge
    # horizon, which the caller chooses and which defaults to 180 days. The
    # comment here used to read "(1-month)" and the UI label followed it; the
    # figure has never been a one-month number.
    var_95: float
    cvar_95: float              # Expected Shortfall in dollars, same horizon
    # Horizon of var_95 / cvar_95. 0 means unknown — do not name a horizon.
    horizon_calendar_days: int = 0
    horizon_trading_days: float = 0.0
    var_pct: float              # VaR as % of notional
    beta: float                 # beta vs SPY
    stress_loss_10pct: float    # dollar loss in a -10% SPY shock (beta-adjusted)
    stress_loss_20pct: float    # dollar loss in a -20% SPY shock (beta-adjusted)


class RiskEstimateProvenance(BaseModel):
    """
    What the risk numbers for one holding were measured from.

    Every field here already existed on `RiskProfile`, which the pipeline
    computes and then discards: `HedgeOutput` carried the beta, the VaR and the
    hedge ratio but nothing about their samples, so a beta fitted on 130
    observations with a wide standard error was presented exactly like one
    fitted on 2,500. The numbers these qualify are the ones that size the
    contracts, so the qualification has to travel with them rather than live
    behind a second request a client may never make.

    None means "not measured" throughout — never zero. An empty string in a
    source field means the same.
    """
    # Is this a measurement at all? False means the whole profile is a
    # placeholder and no figure in it may be read as risk.
    data_available: bool = True
    unavailable_reason: str = ""

    # Beta vs SPY, which sizing multiplies through.
    beta_available: bool = True
    beta_r2: Optional[float] = None
    beta_stderr: Optional[float] = None
    beta_n_obs: Optional[int] = None

    # VaR / expected shortfall.
    var_method: str = ""            # "parametric_cornish_fisher" | "assumed_vol_fallback" | "normal_approximation"
    var_sigma_source: str = ""
    var_n_obs: Optional[int] = None

    # OLS hedge ratio and its basis-risk R².
    hedge_ratio_r2: Optional[float] = None
    hedge_ratio_stderr: Optional[float] = None
    hedge_ratio_n_obs: Optional[int] = None

    # Factor exposure name → why it could not be measured. A populated entry
    # is the difference between "insensitive to rates" and "rate sensitivity
    # unknown", which the response could not previously express.
    factors_unavailable: Dict[str, str] = {}


class HedgeRecommendation(BaseModel):
    rank: int
    asset_ticker: str                   # holding ticker being hedged
    candidates: List[InstrumentCandidate]
    unhedged_risk: Optional[UnhedgedRisk] = None
    # Provenance of the figures in `unhedged_risk` and of the betas and hedge
    # ratios behind `candidates`. None means no risk profile reached L12.
    risk_provenance: Optional[RiskEstimateProvenance] = None


class HedgeOutput(BaseModel):
    portfolio_notional: float
    regime: str
    is_anomaly: bool
    vix_level: float
    recommendations: List[HedgeRecommendation]
    run_time_seconds: float

    # Filled by Layer 5 (LLM Explainer)
    portfolio_summary: str = ""
    key_risks: List[str] = []
    regime_commentary: str = ""
    top_recommendation: str = ""
    llm_provider: str = ""          # which LLM generated the explanations
    llm_notice: str = ""            # user-facing notice when LLM is unavailable

    # Portfolio-level hedge Greeks (Gap 2 — sum of top candidate per holding).
    # These are position-level: L8 scales each candidate by n_contracts x 100
    # and overwrites the per-share value, so summing the top picks is correct.
    hedge_portfolio_delta: float = 0.0
    hedge_portfolio_gamma: float = 0.0
    hedge_portfolio_vega: float = 0.0

    # ── Portfolio-level hedge cost ────────────────────────────────────────────
    # What the recommended hedge set actually costs, against what the user
    # allowed. Each holding is gated individually by L4/L7, but until L10's
    # portfolio check nothing added the per-holding costs up, so the one
    # number a user needs to answer "can I afford this?" was not in the
    # response at all. Negative cost is a net credit across the set.
    hedge_portfolio_cost: float = 0.0
    hedge_budget_total: float = 0.0
    hedge_budget_utilization: float = 0.0   # cost / budget, 1.0 = at the cap

    # ── Valuation provenance ──────────────────────────────────────────────────
    # portfolio_notional above is the server-computed market value (current
    # prices x quantities). These expose what it was derived from so the user
    # can see cost basis vs current exposure rather than trusting one number.
    portfolio_cost_basis: float = 0.0
    portfolio_unrealized_pnl: float = 0.0
    declared_notional: Optional[float] = None       # what the client submitted, if any

    # ── Regime provenance ─────────────────────────────────────────────────────
    # L2 records whether the regime came from the GMM or from the VIX fallback,
    # and why. `regime` above is only the label, so until these were added the
    # response could not distinguish a regime inferred from the full model
    # from one guessed off a single VIX reading — the user saw "mid_vol"
    # either way. A degraded regime changes the regime-fit score of every
    # candidate, so it has to be visible.
    regime_source: str = "gmm_combined"
    regime_degraded: bool = False
    regime_degradation_reason: str = ""

    # ── Data quality ──────────────────────────────────────────────────────────
    # Populated from backend.data.data_quality for the request. Tells the user
    # which inputs were live, cached, substituted or unavailable. Empty dict
    # means no ledger was active (direct engine call), NOT "all live".
    data_quality: Dict[str, Any] = {}
    warnings: List[str] = []        # user-facing data/valuation caveats
